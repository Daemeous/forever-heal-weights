"""Build docs/talents.js: Forever healer talents the stat-weight model needs, keyed by the talent entry IDs that
COMBATANT_INFO logs (node, entry, rank). Entry -> spell -> talent name comes from the client trait tables; the per-rank
VALUES come from the talent descriptions on wowforevertalents.com (talents_all.json), because the client's effect values
are inconsistent (some store rank 1, some the max rank)."""
import csv, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.abspath(os.path.join(HERE, "..", ".."))
BUILD = sys.argv[1] if len(sys.argv) > 1 else "1.60.1.70959"
D = os.path.join(PROJ, "client_data", BUILD)
rd = lambda t: list(csv.DictReader(open(os.path.join(D, t + ".csv"), encoding="utf-8")))
CLASSES = ("Priest", "Paladin", "Shaman", "Druid")

N = r"(\d+(?:\.\d+)?)"
RULES = [  # (regex on the lower-cased rank description, key, how to read the match)
    (r"increases your (?:total )?intellect by " + N + "%", "int"),
    (r"allows " + N + "% of your mana regeneration to continue while casting", "casting"),
    (r"increases your spell healing by up to " + N + "% of your total spirit", "sg"),
    (r"increases your (?:total )?spirit by " + N + "%", "spi"),
    (r"spell damage and healing by up to " + N + "% of your intellect", "intHeal"),
    (r"increases your spell healing by " + N + "% of your intellect", "intHeal"),     # Druid Natural Instinct
]
HEAL = [  # healing multipliers -> scope
    (r"increases the amount healed by your spells by " + N + "%", "all"),
    (r"increases the (?:effect|effectiveness) of (?:all )?your healing spells by " + N + "%", "all"),
    (r"damage and healing of your instant cast spells by " + N + "%", "instant"),
    (r"periodic damage and healing done by your spells and abilities by " + N + "%", "periodic"),
    (r"increases the amount healed by your (.+?) spells? by " + N + "%", "list"),
    (r"increases the effect of your ([a-z' ]+?) spell by " + N + "%", "list"),
    (r"increases the effect of your healing stream totem by " + N + "%", "hst"),
]


def parse(desc):
    d = desc.lower()
    out = {}
    for rx, key in RULES:
        m = re.search(rx, d)
        if m:
            out[key] = float(m.group(1))
    heal = []
    for rx, scope in HEAL:
        for m in re.finditer(rx, d):
            if scope == "list":
                names = [x.strip() for x in re.split(r",\s*(?:and\s+)?|\s+and\s+", m.group(1)) if x.strip()]
                heal.append({"spells": [n.title().replace("'S", "'s") for n in names], "pct": float(m.group(2))})
            elif scope == "hst":
                heal.append({"spells": ["Healing Stream"], "pct": float(m.group(1))})
            else:
                heal.append({scope: 1, "pct": float(m.group(1))})
    # a list match that is really "your spells" etc. is caught by the specific rules first; drop duplicates by pct+scope
    seen, uniq = set(), []
    for h in heal:
        k = json.dumps(h, sort_keys=True)
        if k not in seen:
            seen.add(k); uniq.append(h)
    if uniq:
        out["heal"] = uniq
    return out


site = {}
for c in json.load(open(os.path.join(PROJ, "talents_all.json"), encoding="utf-8")):
    if c["name"] in CLASSES:
        for tr in c["trees"]:
            for t in tr["talents"]:
                site[(c["name"], t["name"])] = t

names = {r["ID"]: r["Name_lang"] for r in rd("SpellName")}
tdef = {r["ID"]: r["SpellID"] for r in rd("TraitDefinition")}
talents, entries = [], {}
index = {}
for r in rd("TraitNodeEntry"):
    sid = tdef.get(r["TraitDefinitionID"])
    nm = names.get(sid or "")
    if not nm:
        continue
    for cls in CLASSES:
        t = site.get((cls, nm))
        if not t:
            continue
        key = (cls, nm)
        if key not in index:
            ranks = [parse(x["description"]) for x in t["ranks"]]
            if not any(ranks):
                index[key] = None
                continue
            index[key] = len(talents)
            talents.append({"n": nm, "c": cls, "r": ranks})
        if index[key] is not None:
            entries[r["ID"]] = index[key]

dst = os.path.join(HERE, "..", "docs", "talents.js")
with open(dst, "w") as fh:
    fh.write("// Generated by tools/gen_talents.py (client trait tables + wowforevertalents.com descriptions) - do not edit.\n")
    fh.write("var FOREVER_TALENTS = " + json.dumps({"meta": {"build": BUILD}, "entries": entries, "talents": talents},
                                                 separators=(",", ":"), sort_keys=True) + ";\n")
    fh.write("if (typeof module !== 'undefined') module.exports = FOREVER_TALENTS;\n")
print(len(talents), "talents,", len(entries), "entries,", os.path.getsize(dst), "bytes")
for t in talents:
    print(f"  {t['c']:8} {t['n']:28} {len(t['r'])} ranks  max: {t['r'][-1]}")
