"""Build docs/spells.js from the cached Forever client tables (run from the parent project).
Every spell that heals, learnable by Priest/Paladin/Shaman/Druid (plus the spells they trigger), keyed by the
spell ID that appears in SPELL_HEAL / SPELL_PERIODIC_HEAL events."""
import json, os, sys
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
from _forever_db import DB
from _rank_data import EXTRA_HEAL

BUILD = sys.argv[1] if len(sys.argv) > 1 else "1.60.1.70959"
db = DB(BUILD)
out = {}

def add(heal_id, cls, learn, cast_id, effs=None):
    effs = effs or db.heal_effects(heal_id)
    rec = out.get(str(heal_id)) or dict(n=db.names.get(str(heal_id)), c=cls, l=learn)
    for e in effs:
        if e["kind"] == "absorb":
            continue
        key = "h" if e["kind"] == "hot" else "d"
        base = e["base"] if key == "h" else (e["low"] + e["high"]) / 2
        if key in rec or (base <= 0 and e["coef"] <= 0):
            continue
        v = [round(base, 2), round(e["coef"], 4)]
        if e["chain"]:
            v.append(round(e["chain_amp"], 3))
        rec[key] = v
    if "d" in rec or "h" in rec:
        out[str(heal_id)] = rec

for cls, ids in db.learn.items():
    for sid in ids:
        sp = db.spell(sid)
        learn = sp["base_level"]
        if learn <= 0:
            continue
        add(sid, cls, learn, sid)
        if sp["name"] == "Prayer of Mending":
            add(sid, cls, learn, sid, [dict(sp["effects"][0], kind="direct")])
        for e in sp["effects"]:                       # triggered heal spells (Holy Nova, Penance, ...)
            t = e["trigger"]
            if t and t != "0" and t in db.names:
                add(t, cls, learn, sid)
        if str(sid) in EXTRA_HEAL:
            add(EXTRA_HEAL[str(sid)], cls, learn, sid)

# heal spells the client links to their cast spell only implicitly
def dummy(heal_id, cast_id):                      # Prayer of Mending: heal amount lives in the cast's dummy effect
    sp = db.spell(cast_id); e = sp["effects"][0]
    out[str(heal_id)] = dict(n=sp["name"], c="Priest", l=sp["base_level"], d=[round(e["base"], 2), round(e["coef"], 4)])
dummy(401863, 401859); dummy(1313379, 1240826); dummy(1313381, 1240827)
for hid, lvl in ((5672, 20), (6371, 30), (6372, 40), (10460, 50), (10461, 60)):   # Healing Stream (totem ticks)
    e = db.heal_effects(hid)[0]
    out[str(hid)] = dict(n="Healing Stream", c="Shaman", l=lvl, h=[round(e["base"], 2), round(e["coef"], 4)])
fh = db.heal_effects(10917)[0]                    # Holy Binding: heals the Priest for 50% of the Flash Heal
out["1328570"] = dict(n="Holy Binding", c="Priest", l=56, d=[round((fh["low"] + fh["high"]) / 4, 2), round(fh["coef"] / 2, 4)])
out["1328622"] = dict(n="Bloom", c="Druid", l=60, spirit=1)   # Bloom heals for the Druid's Spirit (24 Nov 2026 log)

meta = dict(build=BUILD, level=60, n=len(out))
dst = os.path.join(os.path.dirname(__file__), "..", "docs", "spells.js")
os.makedirs(os.path.dirname(dst), exist_ok=True)
with open(dst, "w") as fh:     # a .js file (not .json) so the page also works opened straight from disk
    fh.write("// Generated by tools/gen_spells.py from the Forever client tables - do not edit.\n")
    fh.write("var FOREVER_SPELLS = " + json.dumps(dict(meta=meta, spells=out), separators=(",", ":"), sort_keys=True) + ";\n")
    fh.write("if (typeof module !== 'undefined') module.exports = FOREVER_SPELLS;\n")
print(meta, os.path.getsize(dst), "bytes")
