"""Build docs/items.js: every equippable Forever item with a stat a healer scores (healing / spell power, crit,
Intellect, Spirit, MP5), from the parent project's item decoder (client ItemSparse + Wowhead Forever tooltips +
wowtbc.gg Forever gear data, in that order of trust - see _items.py)."""
import json, os, sys
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
import _items

BUILD = sys.argv[1] if len(sys.argv) > 1 else "1.60.1.70959"
TIER = {"Pre-raid": "P", "PvP": "V", "Raid": "R", "Later": "L", "Other faction": "F"}
# items with an on-use / proc effect in docs/procs.js are kept even without scored stats (relics, trinkets)
_pj = open(os.path.join(os.path.dirname(__file__), "..", "docs", "procs.js"), encoding="utf-8").read()
_pd = json.loads(_pj[_pj.index("{"):_pj.rindex("};") + 1])
# ... and so are pieces of a set with a scored bonus (they count towards the bonus)
PROC_IDS = set(_pd["items"]) | {str(i) for st in _pd.get("sets", {}).values() for i in st["items"]}
out = {}
for it in _items.all_items(BUILD):
    st = it["stats"]
    heal = st.get("HealingPower", 0) + st.get("SpellPower", 0)
    vals = [heal, st.get("CritRating", 0) / 14, st.get("Intellect", 0), st.get("Spirit", 0), st.get("MP5", 0)]
    if not any(vals) and str(it["id"]) not in PROC_IDS:
        continue
    c, sc = it["cls_sub"]
    # [name, inventory type, item class, subclass, required level, quality, healing, % crit (Forever items only give whole / half percents), Int, Spirit, MP5,
    #  allowed-class mask (-1 any), unique, source tiers, source text]
    out[str(it["id"])] = [it["name"], it["inv"], c, sc, it["req_level"], it["quality"]] + [round(v, 2) if i == 1 else round(v) for i, v in enumerate(vals)] + \
                         [it["allow"] if it["allow"] not in (0,) else -1, 1 if it.get("unique") else 0]
    # where it comes from: tiers P (dungeon / quest / crafted / rep / vendor), V PvP, R Classic raid (not in Forever's
    # raids), L later content, F other faction; "" = no known source. Plus a short source text.
    srcs = it.get("sources") or []
    out[str(it["id"])] += ["".join(sorted({TIER.get(x["tier"], "") for x in srcs})), _items.source_text(srcs)[:90]]
dst = os.path.join(os.path.dirname(__file__), "..", "docs", "items.js")
with open(dst, "w", encoding="utf-8") as fh:
    fh.write("// Generated by tools/gen_items.py - do not edit.\n")
    fh.write("var FOREVER_ITEMS = " + json.dumps({"meta": {"build": BUILD, "n": len(out)}, "items": out},
                                               separators=(",", ":"), ensure_ascii=False) + ";\n")
    fh.write("if (typeof module !== 'undefined') module.exports = FOREVER_ITEMS;\n")
print(len(out), "items,", os.path.getsize(dst), "bytes")
